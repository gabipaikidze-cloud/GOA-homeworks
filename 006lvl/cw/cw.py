# 1) შექმენი ორი ცვლადი, სადაც მომხმარებელს შემოატანინებ რიცხვებს.
num1 = input("Enter first number: ")
num2 = input("Enter second number: ")


# 2) პირველ დავალებაში შექმნილი ცვლადები გადაიყვანე ინტეჯერად,
# რომ მოახდინო მათემატიკური მოქმედებები.
num1 = int(num1)
num2 = int(num2)


# 3) დაბეჭდე ყველა მათემატიკური მოქმედება
# (+, -, *, /, %, //)
print(num1 + num2)
print(num1 - num2)
print(num1 * num2)
print(num1 / num2)
print(num1 % num2)
print(num1 // num2)


# 4) შექმენი ცვლადები, სადაც მომხმარებელს შემოატანინებ სახელს და ასაკს.
name = input("Enter your name: ")
age = input("Enter your age: ")


# 5) დაბეჭდე f-string-ით:
# "My name is {მომხმარებლის სახელი} and my age is {მომხმარებლის ასაკი}"
print(f"My name is {name} and my age is {age}")

