# 3) reverse()
numbers2 = [10, 20, 30, 40, 50]
numbers2.reverse()
print(numbers2)


# 4) reverse()
languages = ["HTML", "CSS", "JavaScript", "Python"]
languages.reverse()
print(languages)


# 5) count()
numbers3 = [1, 2, 3, 2, 4, 2, 5, 2]
print(numbers3.count(2))


# 6) count()
fruits2 = ["apple", "banana", "apple", "orange", "apple", "banana"]
print("Apple:", fruits2.count("apple"))
print("Banana:", fruits2.count("banana"))


