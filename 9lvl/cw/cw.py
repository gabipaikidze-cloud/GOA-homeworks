# 1) მომხმარებელს შემოატანინე თავისი ასაკი,
# შემდეგ შეამოწმე არის თუ არა ასაკი 18-ის მეტი ან ტოლი.
# თუ არის, კონსოლში გამოვიდეს "სრულწლოვანი ხართ".
age = int(input("შეიყვანე შენი ასაკი: "))

if age >= 18:
    print("სრულწლოვანი ხართ")


# 2) მომხმარებელს შემოატანინე ორი რიცხვი (num1, num2).
# თუ num1 მეტია num2-ზე, გამოვიდეს "პირველი რიცხვი მეტია".
num1 = int(input("შეიყვანე პირველი რიცხვი: "))
num2 = int(input("შეიყვანე მეორე რიცხვი: "))

if num1 > num2:
    print("პირველი რიცხვი მეტია")


# 3) მომხმარებელს კითხე რა არის სწორი რიცხვი.
# თუ რიცხვი უდრის 777-ს, დაბეჭდოს "რიცხვი გამოცნობილია".
number = int(input("რა არის სწორი რიცხვი? "))

if number == 777:
    print("რიცხვი გამოცნობილია")


# 4) მომხმარებელს შემოატანინე თავისი სიმაღლე.
# თუ სიმაღლე მეტია ან უდრის 1.70-ს, დაბეჭდოს "შენ მაღალი ხარ".
height = float(input("შეიყვანე შენი სიმაღლე: "))

if height >= 1.70:
    print("შენ მაღალი ხარ")
